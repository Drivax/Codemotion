 await expect(page.locator('.doc-guides')).toContainText('lien devenu invalide');
 await page.getByRole('button', { name: 'Réparer « Découverte du projet »' }).click();
 const save = page.getByRole('button', { name: 'Enregistrer les cibles validées' });
 await expect(save).toBeDisabled();
