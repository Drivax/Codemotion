 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
 const old = await project(page);
 await expect(page.getByRole('button', { name: /À propos/ })).toBeVisible();
 await page.screenshot({ path: path.resolve(__dirname, '../../docs/navigation-v4-home.png') });
 await page.getByRole('button', { name: /Commencer ici/ }).click();
 await expect(page.locator('.doc-prose li')).toHaveCount(2);
 await expect(page.locator('.doc-prose table')).toContainText('entrée');
 await expect(page.locator('.doc-prose pre')).toContainText('print("exemple")');
 await page.getByText('Générer depuis plusieurs sections', { exact: true }).click();
 await page.locator('.doc-guides').getByLabel('Démarrer', { exact: true }).check();
 await page.locator('.doc-guides').getByLabel('Architecture', { exact: true }).check();
 await page.getByRole('button', { name: 'Ajouter les sections sélectionnées au guide' }).click();
 await page.getByLabel('Note de l’étape 1', { exact: true }).fill('Vérifier l’appel');
 await page.getByText('Relations statiques entre les étapes', { exact: true }).click();
 await expect(page.locator('.doc-guides')).toContainText('CALLS (resolved)');
 await page.getByRole('button', { name: 'Enregistrer le guide', exact: true }).click();
 await page.getByRole('button', { name: 'Reprendre le guide' }).click();
 await page.getByLabel('Étape terminée', { exact: true }).check();
 await expect(page.getByLabel('Note de l’étape active')).toHaveValue('Vérifier l’appel');
 await page.getByRole('button', { name: 'Étape suivante du guide' }).click();
 await expect(page.getByRole('navigation', { name: 'Définitions ouvertes' }).getByRole('button', { name: 'entry', exact: true })).toBeVisible();
 await page.getByRole('navigation', { name: 'Définitions ouvertes' }).getByRole('button', { name: 'entry', exact: true }).focus();
 await expect(page.getByRole('complementary', { name: 'Aperçu de la définition' })).toContainText('def entry');
 await page.keyboard.press('Escape');
