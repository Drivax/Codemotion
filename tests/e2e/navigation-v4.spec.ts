import { expect, test, type Page } from '../../frontend/node_modules/@playwright/test';
import path from 'node:path';
const base = 'http://127.0.0.1:8000/api';
async function project(page: Page, moved = false) {
 const file = moved ? 'new.py' : 'main.py';
 const readme = '# Présentation\nProjet de test.\n## Démarrer\n`entry`\n- Lire le code\n- Choisir une branche\n\n| Action | Rôle |\n| --- | --- |\n| entrée | démarrer |\n\n```python\nprint("exemple")\n```\n## Architecture\n`helper`\n[ancien fichier](main.py)';
 const job = await (await page.request.post(base + '/repositories/import', { data: { name: 'navigation-v4', files: { [file]: 'def helper(x): return x + 1\ndef entry(x): return helper(x)\n', 'README.md': readme } } })).json();
 let id = ''; await expect.poll(async () => { const j = await (await page.request.get(base + '/jobs/' + job.id)).json(); id = j.repository_id; return j.status; }).toBe('completed');
 const summary = await (await page.request.get(base + '/repositories/' + id)).json();
 const symbols = await (await page.request.get(base + '/repositories/' + id + '/symbols')).json();
 const entry = symbols.items.find((n: { name: string }) => n.name === 'entry');
 await page.goto('/#codemotion=' + encodeURIComponent(JSON.stringify({ format: 1, repository: id, snapshot: summary.repository.snapshot, state: { view: { mode: 'objects', selected: entry.id, flowId: null, playback: null } } })));
 await expect(page.locator('.repo-title')).toContainText('navigation-v4');
 await page.getByRole('button', { name: 'Comprendre', exact: true }).click();
 return summary.repository.snapshot as string;
}
